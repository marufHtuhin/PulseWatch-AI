import { useState } from 'react'
import { Link, useParams } from 'react-router-dom'
import {
  ArrowLeft,
  Bot,
  Check,
  CheckCheck,
  Clock,
  ExternalLink,
  Gauge,
  Lightbulb,
  Repeat,
  Sparkles,
  Wrench,
} from 'lucide-react'
import { useApi } from '../hooks/useApi'
import { acknowledgeAlert, apiErrorMessage, getAlert, listMonitorHistory, resolveAlert } from '../api/client'
import { useToast } from '../components/Toast'
import { ChartCard, ErrorState, LoadingSkeleton, PageHeader } from '../components/Cards'
import { AlertStatusBadge, MethodBadge, SeverityBadge } from '../components/Badges'
import { ResponseTimeChart } from '../components/Charts'
import { anomalyLabel, formatBytes, formatDateTime, formatMs, timeAgo } from '../utils/format'

export function AlertDetail() {
  const { id } = useParams()
  const toast = useToast()
  const [busy, setBusy] = useState(false)

  const alert = useApi(() => getAlert(id), [id], { pollIntervalMs: 30000 })
  const a = alert.data

  // Related monitoring history for the alert's monitor (latest checks).
  const history = useApi(
    () => (a?.monitor_id ? listMonitorHistory(a.monitor_id, { page: 1, page_size: 20 }) : Promise.resolve({ items: [] })),
    [a?.monitor_id],
    { pollIntervalMs: 30000, initialData: { items: [] } }
  )
  const records = history.data?.items || []

  const handleAction = async (action) => {
    if (!a) return
    setBusy(true)
    try {
      if (action === 'acknowledge') {
        await acknowledgeAlert(a.id)
        toast.success('Alert acknowledged.')
      } else {
        await resolveAlert(a.id)
        toast.success('Alert resolved.')
      }
      alert.refetch()
    } catch (err) {
      toast.error(apiErrorMessage(err, `Could not ${action} the alert`))
    } finally {
      setBusy(false)
    }
  }

  if (alert.loading && !a) {
    return (
      <div>
        <PageHeader title="Alert" />
        <LoadingSkeleton rows={6} />
      </div>
    )
  }

  if (alert.error) {
    return (
      <div>
        <PageHeader title="Alert" />
        <div className="card">
          <ErrorState message={alert.error} onRetry={alert.refetch} />
        </div>
        <Link to="/alerts" className="btn-secondary mt-4">
          <ArrowLeft className="h-4 w-4" />
          Back to alerts
        </Link>
      </div>
    )
  }

  const monitor = a.monitor || {}
  const anomaly = a.anomaly || {}
  const record = a.record || {}

  return (
    <div>
      <PageHeader
        title={a.title}
        description={
          <span className="flex flex-wrap items-center gap-2">
            <SeverityBadge severity={a.severity} />
            <AlertStatusBadge status={a.status} />
            <span className="text-xs text-zinc-500">
              {anomalyLabel(a.anomaly_type)} · detected {timeAgo(a.created_at)}
            </span>
          </span>
        }
        actions={
          <>
            <Link to="/alerts" className="btn-secondary">
              <ArrowLeft className="h-4 w-4" />
              All alerts
            </Link>
            {a.status === 'active' && (
              <button className="btn-secondary" onClick={() => handleAction('acknowledge')} disabled={busy}>
                <Check className="h-4 w-4" />
                Acknowledge
              </button>
            )}
            {a.status !== 'resolved' && (
              <button className="btn-primary" onClick={() => handleAction('resolve')} disabled={busy}>
                <CheckCheck className="h-4 w-4" />
                Resolve
              </button>
            )}
          </>
        }
      />

      <div className="grid grid-cols-1 gap-6 xl:grid-cols-3">
        <div className="space-y-6 xl:col-span-2">
          {/* AI explanation */}
          <ChartCard
            title="AI explanation"
            subtitle={a.ai_generated ? 'Generated by AI from check metadata' : 'Deterministic explanation (AI unavailable for this alert)'}
            action={
              <span className="inline-flex items-center gap-1.5 rounded-full border border-zinc-200 bg-zinc-50 px-2.5 py-1 text-xs font-medium text-zinc-600">
                {a.ai_generated ? <Sparkles className="h-3.5 w-3.5" /> : <Bot className="h-3.5 w-3.5" />}
                {a.ai_generated ? 'AI generated' : 'Template'}
              </span>
            }
          >
            <div className="space-y-5">
              <div>
                <h3 className="flex items-center gap-2 text-sm font-semibold text-zinc-900">
                  <Bot className="h-4 w-4 text-zinc-400" />
                  What happened
                </h3>
                <p className="mt-1.5 text-sm leading-relaxed text-zinc-700">
                  {a.summary || 'No summary was provided for this alert.'}
                </p>
              </div>
              <div>
                <h3 className="flex items-center gap-2 text-sm font-semibold text-zinc-900">
                  <Lightbulb className="h-4 w-4 text-zinc-400" />
                  Possible cause
                </h3>
                <p className="mt-1.5 text-sm leading-relaxed text-zinc-700">
                  {a.possible_cause || 'No possible cause was provided.'}
                </p>
              </div>
              <div>
                <h3 className="flex items-center gap-2 text-sm font-semibold text-zinc-900">
                  <Wrench className="h-4 w-4 text-zinc-400" />
                  Recommended action
                </h3>
                <p className="mt-1.5 text-sm leading-relaxed text-zinc-700">
                  {a.recommended_action || 'No recommended action was provided.'}
                </p>
              </div>
            </div>
          </ChartCard>

          {/* Response metrics at detection */}
          <ChartCard title="Response metrics at detection" subtitle="From the check that raised this alert">
            {record && record.id ? (
              <dl className="grid grid-cols-2 gap-4 text-sm sm:grid-cols-4">
                <Metric label="Status code" value={record.status_code ?? '—'} mono />
                <Metric label="Response time" value={formatMs(record.response_time_ms)} />
                <Metric label="Response size" value={formatBytes(record.response_size_bytes)} />
                <Metric
                  label="Records returned"
                  value={record.records_returned ?? '—'}
                />
                <Metric label="Valid JSON" value={record.is_valid_json == null ? '—' : record.is_valid_json ? 'Yes' : 'No'} />
                <Metric label="Content type" value={record.content_type || '—'} mono />
                <Metric label="Checked at" value={formatDateTime(record.checked_at)} />
                <Metric label="Error" value={record.error_message || 'None'} />
              </dl>
            ) : (
              <p className="text-sm text-zinc-500">
                The originating check record is not attached to this alert.
              </p>
            )}
          </ChartCard>

          {/* Related monitoring history */}
          <ChartCard title="Recent checks on this monitor" subtitle="Response times around the alert">
            {history.loading && !history.data ? (
              <div className="h-[220px] animate-pulse rounded-lg bg-zinc-200/50" />
            ) : (
              <ResponseTimeChart points={records} singleSeries height={220} />
            )}
          </ChartCard>
        </div>

        <div className="space-y-6">
          {/* Monitor info */}
          <ChartCard title="Monitor">
            <dl className="space-y-3 text-sm">
              <InfoRow
                label="Name"
                value={
                  <Link to={`/monitors/${a.monitor_id}`} className="font-medium text-zinc-900 hover:text-blue-600">
                    {a.monitor_name || monitor.name || `Monitor #${a.monitor_id}`}
                  </Link>
                }
              />
              {monitor.method && <InfoRow label="Method" value={<MethodBadge method={monitor.method} />} />}
              {monitor.url && (
                <InfoRow
                  label="URL"
                  value={
                    <a
                      href={monitor.url}
                      target="_blank"
                      rel="noreferrer"
                      className="inline-flex items-center gap-1 break-all font-mono text-xs text-zinc-700 hover:text-blue-600"
                    >
                      {monitor.url}
                      <ExternalLink className="h-3 w-3 shrink-0" />
                    </a>
                  }
                />
              )}
              <InfoRow label="Anomaly type" value={anomalyLabel(a.anomaly_type)} />
              {anomaly.description && <InfoRow label="Anomaly detail" value={anomaly.description} />}
              {anomaly.severity && <InfoRow label="Anomaly severity" value={<SeverityBadge severity={anomaly.severity} />} />}
            </dl>
          </ChartCard>

          {/* Occurrence + timeline */}
          <ChartCard title="Occurrence & timeline">
            <dl className="space-y-3 text-sm">
              <InfoRow
                label="Occurrences"
                value={
                  <span className="inline-flex items-center gap-1.5">
                    <Repeat className="h-4 w-4 text-zinc-400" />
                    {a.occurrence_count ?? 1} time{(a.occurrence_count ?? 1) === 1 ? '' : 's'}
                  </span>
                }
              />
              <InfoRow label="Last seen" value={a.last_seen_at ? `${formatDateTime(a.last_seen_at)} (${timeAgo(a.last_seen_at)})` : '—'} />
              <InfoRow
                label="First detected"
                value={
                  <span className="inline-flex items-center gap-1.5">
                    <Clock className="h-4 w-4 text-zinc-400" />
                    {formatDateTime(a.created_at)}
                  </span>
                }
              />
              <InfoRow
                label="Acknowledged"
                value={a.acknowledged_at ? formatDateTime(a.acknowledged_at) : 'Not acknowledged'}
              />
              <InfoRow
                label="Resolved"
                value={a.resolved_at ? formatDateTime(a.resolved_at) : 'Not resolved'}
              />
            </dl>
            <p className="mt-4 border-t border-zinc-200 pt-3 text-xs leading-relaxed text-zinc-400">
              Recurring anomalies of the same type on this monitor don&apos;t open a new alert while this one is
              active or acknowledged — they increment the occurrence count and update &ldquo;last seen&rdquo; instead.
            </p>
          </ChartCard>

          {/* Quick actions */}
          <div className="card p-4">
            <h3 className="text-sm font-semibold text-zinc-900">Monitor actions</h3>
            <div className="mt-3 flex flex-col gap-2">
              <Link to={`/monitors/${a.monitor_id}`} className="btn-secondary w-full justify-start">
                <Gauge className="h-4 w-4" />
                Open monitor detail
              </Link>
              <Link to={`/monitors/${a.monitor_id}/edit`} className="btn-secondary w-full justify-start">
                <Wrench className="h-4 w-4" />
                Adjust monitor thresholds
              </Link>
            </div>
          </div>
        </div>
      </div>
    </div>
  )
}

function Metric({ label, value, mono = false }) {
  return (
    <div>
      <dt className="text-[11px] font-medium uppercase tracking-wider text-zinc-400">{label}</dt>
      <dd className={`mt-1 font-medium text-zinc-900 ${mono ? 'break-all font-mono text-xs' : ''}`}>{value}</dd>
    </div>
  )
}

function InfoRow({ label, value }) {
  return (
    <div className="flex items-start justify-between gap-3">
      <dt className="shrink-0 text-zinc-500">{label}</dt>
      <dd className="text-right text-zinc-900">{value}</dd>
    </div>
  )
}
